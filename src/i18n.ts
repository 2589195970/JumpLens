export const messages: Record<Locale, Messages> = { zh, en, ko };

/** Chinese stays the default when Orca reports no language; any language other than Chinese or Korean reads English. */
export function resolveLocale(tag: string | undefined): Locale {
  const language = tag?.trim().toLowerCase().split(/[-_]/)[0];
  if (!language || language === 'zh') return 'zh';
  return language === 'ko' ? 'ko' : 'en';
}

let current: Locale = 'zh';
export function setLocale(tag: string | undefined): Locale { current = resolveLocale(tag); return current; }
export function currentLocale(): Locale { return current; }

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = messages[current][key];
  return params ? template.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match) : template;
}
